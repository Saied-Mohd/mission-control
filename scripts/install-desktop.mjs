#!/usr/bin/env node
// Adds Mission Control to the Linux app menu as its own window (Chromium-family --app mode).
// Opens the local server (http://127.0.0.1:4317) and makes sure the mc-serve service is running.
//   node scripts/install-desktop.mjs            install
//   node scripts/install-desktop.mjs --remove   uninstall
//   --url <url>  use a different URL (e.g. the GitHub Pages app)

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const HOME = os.homedir();
const APPS = path.join(HOME, '.local', 'share', 'applications');
const ICONS = path.join(HOME, '.local', 'share', 'icons', 'hicolor');
const DESKTOP = path.join(APPS, 'mission-control.desktop');
const LAUNCHER = path.join(HOME, '.local', 'bin', 'mission-control');
const args = process.argv.slice(2);
const urlArg = args.includes('--url') ? args[args.indexOf('--url') + 1] : null;

const refresh = () => {
  for (const [cmd, a] of [['update-desktop-database', [APPS]], ['gtk-update-icon-cache', ['-q', '-t', ICONS]]]) {
    try {
      execFileSync(cmd, a, { stdio: 'ignore' });
    } catch {}
  }
};

if (args.includes('--remove')) {
  for (const f of [DESKTOP, LAUNCHER, path.join(ICONS, '512x512/apps/mission-control.png'), path.join(ICONS, '192x192/apps/mission-control.png')]) fs.rmSync(f, { force: true });
  refresh();
  console.log('✓ Mission Control removed from the app menu');
  process.exit(0);
}

const BROWSERS = ['brave-browser', 'google-chrome', 'google-chrome-stable', 'chromium', 'chromium-browser', 'microsoft-edge'];
const which = (b) => {
  try {
    return execFileSync('which', [b], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch {
    return null;
  }
};
const browser = BROWSERS.map(which).find(Boolean);
const url = urlArg || 'http://127.0.0.1:4317/';

for (const size of ['512x512', '192x192']) {
  const dir = path.join(ICONS, size, 'apps');
  fs.mkdirSync(dir, { recursive: true });
  fs.copyFileSync(path.join(ROOT, 'app', 'icons', size === '512x512' ? 'icon-512.png' : 'icon-192.png'), path.join(dir, 'mission-control.png'));
}

// Launcher: start the local service if needed, then open an app window (or the default browser).
const open = browser
  ? `exec "${browser}" --app="$URL" --class=MissionControl --user-data-dir="$HOME/.local/share/mission-control/browser" "$@"`
  : `exec xdg-open "$URL"`;
fs.writeFileSync(
  LAUNCHER,
  `#!/bin/sh
# Mission Control desktop launcher (generated by scripts/install-desktop.mjs)
URL="\${MC_URL:-${url}}"
case "$URL" in
  http://127.0.0.1*|http://localhost*)
    systemctl --user start mc-serve.service 2>/dev/null
    i=0; while [ $i -lt 20 ] && ! curl -s -o /dev/null -H 'X-MC: 1' "\${URL}api/info"; do sleep 0.25; i=$((i+1)); done ;;
esac
${open}
`,
  { mode: 0o755 },
);

fs.mkdirSync(APPS, { recursive: true });
fs.writeFileSync(
  DESKTOP,
  `[Desktop Entry]
Type=Application
Name=Mission Control
GenericName=Project command deck
Comment=Boards, agent logs, approvals, vault and Claude's brain
Exec=${LAUNCHER}
Icon=mission-control
Terminal=false
Categories=Development;ProjectManagement;
Keywords=projects;kanban;agents;claude;vault;
StartupWMClass=MissionControl
Actions=Deck;Approvals;

[Desktop Action Deck]
Name=Open the deck
Exec=env MC_URL=http://127.0.0.1:4317/deck/ ${LAUNCHER}

[Desktop Action Approvals]
Name=Approvals
Exec=env "MC_URL=http://127.0.0.1:4317/#/approvals" ${LAUNCHER}
`,
);
refresh();
console.log(`✓ Mission Control added to your app menu`);
console.log(`  opens ${url} ${browser ? `in its own ${path.basename(browser)} window` : 'in your default browser'}`);
console.log(`  launcher: ${LAUNCHER}   (remove: npm run uninstall:desktop)`);
